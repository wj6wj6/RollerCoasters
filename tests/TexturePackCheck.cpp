int failures = 0;

void check(bool ok, const char *what)
{
    std::printf("%s: %s\n", ok ? "ok" : "FAILED", what);
    if (!ok)
        ++failures;
}

std::string text()
{
    std::string t;
    for (int k = 0; k < 40; ++k)
        t += "Roller coasters ride over block islands. ";
    for (int b = 0; b < 256; ++b)
        t += static_cast<char>(b);
    return t;
}

std::string letters()
{
    const char *alphabet = "etaoinshrdlu";
    std::string t;
    for (long i = 0; i < 4000; ++i)
        t += alphabet[(i * i * 7 + i * 13) % 12];
    return t;
}

bool inflatesTo(const unsigned char *data, size_t size, const std::string &expected)
{
    ZipArchive::Bytes out;
    return ZipArchive::inflate(data, size, out) && std::string(out.begin(), out.end()) == expected;
}

void write(const fs::path &path, const unsigned char *data, size_t size)
{
    fs::create_directories(path.parent_path());
    std::ofstream out(path, std::ios::binary);
    out.write(reinterpret_cast<const char *>(data), static_cast<std::streamsize>(size));
}

// The colour of the texel at (x, y).
bool texelIs(const PixelArt::Image &image, int x, int y, int r, int g, int b, int a)
{
    const int side = PixelArt::sizeOf(image);
    const size_t i = static_cast<size_t>((y * side + x) * 4);
    return image.size() == static_cast<size_t>(side * side * 4) && image[i] == r &&
           image[i + 1] == g && image[i + 2] == b && image[i + 3] == a;
}

