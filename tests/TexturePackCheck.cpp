int main()
{
    using LandTextures::Texture;

    // DEFLATE
    check(inflatesTo(kStored, sizeof kStored, text()), "stored blocks decode");
    check(inflatesTo(kFixed, sizeof kFixed, text()), "fixed Huffman blocks decode");
    check(inflatesTo(kDynamic, sizeof kDynamic, letters()), "dynamic Huffman blocks decode");
    ZipArchive::Bytes partial;
    check(!ZipArchive::inflate(kDynamic, sizeof kDynamic / 2, partial),
          "a stream cut short is refused");

    // a strip's first frame
    {
        ZipArchive::Bytes file(kStripPng, kStripPng + sizeof kStripPng);
        int width = 0, height = 0;
        std::vector<unsigned char> rgba;
        check(TexturePack::decodePng(file, width, height, rgba) && width == 16 && height == 32,
              "a PNG decodes to its size");
        const PixelArt::Image frame = TexturePack::firstFrame(rgba, width, height);
        check(PixelArt::sizeOf(frame) == 16 && texelIs(frame, 5, 15, 200, 200, 200, 255) &&
                  texelIs(frame, 0, 0, 200, 200, 200, 0),
              "an animated strip gives its top frame");
        ZipArchive::Bytes junk(40, 7);
        check(!TexturePack::decodePng(junk, width, height, rgba),
              "a file that is no PNG is refused");
    }

    const fs::path folder = fs::temp_directory_path() / "rollercoasters-texturepack-check";
    std::error_code error;
    fs::remove_all(folder, error);
    fs::create_directories(folder);

    // a zip pack, one folder down in its archive
    write(folder / "pack.zip", kPackZip, sizeof kPackZip);
    {
        TexturePack::Pack pack;
        check(pack.open((folder / "pack.zip").u8string()), "a zip pack opens");
        check(pack.name() == "pack", "the pack is named after its file");
        check(pack.coverage() == 4, "the zip pack replaces its four textures");
        PixelArt::Image image;
        check(pack.landTexture(Texture::GRASS_TOP, image) && PixelArt::sizeOf(image) == 4 &&
                  texelIs(image, 1, 2, 145, 189, 89, 255),
              "the grey grass top (deflated) is tinted grass green");
        check(pack.landTexture(Texture::STONE, image) && PixelArt::sizeOf(image) == 8 &&
                  texelIs(image, 3, 3, 90, 90, 100, 255),
              "the stone (stored) is used as it is");
        check(pack.landTexture(Texture::LAVA, image) && PixelArt::sizeOf(image) == 16 &&
                  texelIs(image, 0, 0, 200, 200, 200, 255),
              "the lava strip gives its first frame, its hole filled");
        check(pack.landTexture(Texture::DIRT, image) && texelIs(image, 1, 1, 120, 80, 40, 255),
              "a picture in this program's own layout is used");
        check(!pack.landTexture(Texture::WATER, image) &&
                  !pack.landTexture(Texture::BAMBOO, image) &&
                  !pack.landTexture(Texture::GRASS_SIDE, image),
              "what the pack lacks stays built in");
    }

    // a folder pack, one folder down, in the block game's older layout
    write(folder / "Downloaded" / "Inner" / "pack.mcmeta",
          reinterpret_cast<const unsigned char *>("{}"), 2);
    write(folder / "Downloaded" / "Inner" / "assets" / "minecraft" / "textures" / "blocks" /
              "leaves_oak.png",
          kStripPng, sizeof kStripPng);
    {
        TexturePack::Pack pack;
        check(pack.open((folder / "Downloaded").u8string()), "a folder pack opens");
        check(pack.coverage() == 1, "the folder pack replaces its one texture");
        PixelArt::Image image;
        // grey 200 tinted by the foliage colour (119, 171, 47); the hole
        // filled with the average, darker
        check(pack.landTexture(Texture::LEAVES_OAK, image) &&
                  texelIs(image, 4, 4, 93, 134, 36, 255) && texelIs(image, 0, 0, 51, 73, 19, 255),
              "grey leaves are tinted and their holes filled darker");
        TexturePack::Pack empty;
        check(!empty.open(folder.u8string()), "a folder that is no pack is refused");
    }

    const std::vector<TexturePack::Found> found = TexturePack::findIn(folder.u8string());
    check(found.size() == 2 && found[0].name == "Downloaded" && found[1].name == "pack",
          "the folder's packs are listed by name");
    check(std::string(TexturePack::nativeName(Texture::GRASS_TOP)) == "grass_top",
          "the island's textures have names in the pack layout");

    fs::remove_all(folder, error);
    std::printf("%s\n", failures == 0 ? "all ok" : "some checks FAILED");
    return failures == 0 ? 0 : 1;
}
